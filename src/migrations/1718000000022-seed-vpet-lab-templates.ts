import { MigrationInterface, QueryRunner } from 'typeorm'

interface LabField {
  itemCode: string
  itemName: string
  englishAbbr: string
  unit: string
  valueType: 'number' | 'text' | 'select'
  required: boolean
  refMin?: number
  refMax?: number
  referenceText?: string
  defaultValue?: string
  displayOrder: number
  method: string
  specimenRequirement: string
  resultOptions: string[]
  explanation: string
  clinicalSignificance: string
}

interface LabTemplateSeed {
  code: string
  name: string
  category: number
  speciesScope: string
  sampleType: string
  defaultChargeAmount: number
  description: string
  fields: LabField[]
}

function field(
  itemCode: string,
  itemName: string,
  englishAbbr: string,
  unit: string,
  valueType: LabField['valueType'],
  referenceText: string,
  method: string,
  specimenRequirement: string,
  explanation: string,
  clinicalSignificance: string,
  resultOptions: string[] = [],
  refMin?: number,
  refMax?: number,
): Omit<LabField, 'displayOrder'> {
  return {
    itemCode,
    itemName,
    englishAbbr,
    unit,
    valueType,
    required: true,
    refMin,
    refMax,
    referenceText,
    defaultValue: '',
    method,
    specimenRequirement,
    resultOptions,
    explanation,
    clinicalSignificance,
  }
}

function template(
  code: string,
  name: string,
  category: number,
  speciesScope: string,
  sampleType: string,
  defaultChargeAmount: number,
  description: string,
  fields: Array<Omit<LabField, 'displayOrder'>>,
): LabTemplateSeed {
  return {
    code,
    name,
    category,
    speciesScope,
    sampleType,
    defaultChargeAmount,
    description,
    fields: fields.map((item, index) => ({ ...item, displayOrder: index + 1 })),
  }
}

